import { createHash } from 'node:crypto';
import type { IdentityProviderCode } from '../../generated/prisma/client.js';

/**
 * External identity provider boundary (docs/architecture/08-identity-and-verification.md §3).
 *
 * The identity module depends only on this class. Adapters:
 * - `EsignetIdentityProvider` [ABSTRACTION -> EXTERNAL]: OIDC relying party for Fayda via
 *   eSignet. Endpoints come from the provider's discovery document; credentials come from
 *   NIDP onboarding.
 * - `DevIdentityProvider` [IMPL, development/test only]: synthetic identities.
 * - `DisabledIdentityProvider`: fails closed (default outside development).
 *
 * Security-critical values (state, nonce, PKCE verifier) are generated by the identity
 * service, not by adapters, and the service re-checks the nonce and the mapped claims, so
 * a faulty adapter cannot weaken those checks.
 */

export interface AuthorizationRequest {
  /** 256-bit random, single use. */
  readonly state: string;
  /** 256-bit random; must come back inside the signed ID token. */
  readonly nonce: string;
  /** BASE64URL(SHA-256(code_verifier)), method S256. */
  readonly codeChallenge: string;
  /** Exact redirect URI registered with the provider. */
  readonly redirectUri: string;
  readonly locale: 'en' | 'am';
}

export interface CodeExchange {
  readonly code: string;
  readonly codeVerifier: string;
  readonly redirectUri: string;
  /** Aborted when the provider timeout elapses. */
  readonly signal: AbortSignal;
}

/** What a provider proved, after the adapter verified signatures and protocol claims. */
export interface ProviderIdentity {
  /** Stable, provider-specific subject. Hashed (HMAC) before storage; never logged. */
  readonly subject: string;
  /** `nonce` from the verified ID token; compared with the session value by the service. */
  readonly nonce: string | undefined;
  /** e.g. the ID token `acr`. */
  readonly assuranceLevel: string | undefined;
  readonly fullName: string | undefined;
  /** `YYYY-MM-DD`. */
  readonly dateOfBirth: string | undefined;
  /** Names (not values) of the claims received, for the audit trail. */
  readonly claimNames: readonly string[];
}

/** How an `error` returned to the callback should end the attempt. */
export type CallbackErrorKind = 'DECLINED' | 'EXPIRED' | 'FAILED';

export type IdentityProviderFailure =
  | 'TIMEOUT'
  | 'UNAVAILABLE'
  | 'INVALID_RESPONSE'
  | 'INVALID_GRANT'
  // Authenticated, but with an assurance level (`acr`) that is not accepted.
  | 'INSUFFICIENT_ASSURANCE'
  | 'MISCONFIGURED';

/**
 * Typed adapter failure. `detail` is a fixed, non-sensitive description for operators; it
 * never contains tokens, codes, claims or provider messages.
 */
export class IdentityProviderError extends Error {
  constructor(
    readonly kind: IdentityProviderFailure,
    readonly detail: string,
  ) {
    super(`${kind}: ${detail}`);
    this.name = 'IdentityProviderError';
  }
}

export abstract class IdentityProvider {
  /** Stored on each attempt; `null` when no provider is configured. */
  abstract readonly code: IdentityProviderCode | null;
  /** Path segment of the callback route: /identity/callback/<slug>. */
  abstract readonly slug: string;
  abstract readonly available: boolean;

  /** Loads whatever the adapter needs before an attempt starts (e.g. discovery). */
  abstract prepare(signal: AbortSignal): Promise<void>;

  /** Browser URL that starts authentication at the provider. Call `prepare` first. */
  abstract authorizationUrl(request: AuthorizationRequest): string;

  /** Exchanges the one-time code server-side and returns the verified identity. */
  abstract exchange(input: CodeExchange): Promise<ProviderIdentity>;

  /** Maps the provider's callback `error` value. Unknown values must map to FAILED. */
  abstract classifyCallbackError(error: string): CallbackErrorKind;
}

/**
 * Callback error vocabulary of eSignet (VeriFayda 2 relying-party documentation §3.1) plus
 * standard OAuth `access_denied`. Shared by the dev adapter, which imitates eSignet.
 */
export function classifyOidcCallbackError(error: string): CallbackErrorKind {
  switch (error) {
    case 'access_denied':
    case 'consent_request_rejected':
    case 'consent_details_rejected':
      return 'DECLINED';
    case 'transaction_timeout':
    case 'invalid_transaction':
      return 'EXPIRED';
    default:
      return 'FAILED';
  }
}

/** The OIDC redirect URI registered with the provider for this API. */
export function identityCallbackUrl(publicApiBaseUrl: string, slug: string): string {
  return `${publicApiBaseUrl}/api/v1/identity/callback/${slug}`;
}

/** PKCE S256 (RFC 7636 §4.2): BASE64URL(SHA-256(ASCII(code_verifier))), no padding. */
export function pkceChallenge(codeVerifier: string): string {
  return createHash('sha256').update(codeVerifier, 'ascii').digest('base64url');
}

/** Default outside development: identity verification fails closed with 503. */
export class DisabledIdentityProvider extends IdentityProvider {
  readonly code = null;
  readonly slug = 'disabled';
  readonly available = false;

  prepare(): Promise<void> {
    return Promise.reject(new IdentityProviderError('MISCONFIGURED', 'no provider configured'));
  }

  authorizationUrl(): string {
    throw new IdentityProviderError('MISCONFIGURED', 'no provider configured');
  }

  exchange(): Promise<ProviderIdentity> {
    return Promise.reject(new IdentityProviderError('MISCONFIGURED', 'no provider configured'));
  }

  classifyCallbackError(): CallbackErrorKind {
    return 'FAILED';
  }
}
